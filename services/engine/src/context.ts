import { AsyncLocalStorage } from 'node:async_hooks';

/**
 * Who and where the current work is for. Set once at the edge (an API request
 * after the session and membership checks, or a background job iterating
 * workspaces) and read by `home()`, so every module that stores data lands in
 * the right workspace without having to pass it around — and can't forget to.
 */

export type Role = 'owner' | 'admin' | 'editor' | 'viewer';

export interface WorkContext {
  workspace?: string;
  user?: string;
  role?: Role;
}

const store = new AsyncLocalStorage<WorkContext>();

let processDefault: WorkContext | undefined;

/** The current request's or job's context; else the process default (a command-line tool working in one workspace). */
export const currentContext = (): WorkContext | undefined => store.getStore() ?? processDefault;

/** For command-line tools: work in this workspace for the rest of the process. Requests and jobs still use their own. */
export function setProcessContext(ctx: WorkContext | undefined) {
  if (ctx?.workspace !== undefined && !isId(ctx.workspace)) throw new Error('bad workspace id');
  processDefault = ctx ? { ...ctx } : undefined;
}

/** Workspace and user ids are generated by us; anything else is refused before it can become a path. */
export const isId = (s: unknown): s is string => typeof s === 'string' && /^[uw][a-z0-9]{8,40}$/.test(s);

export function runAs<T>(ctx: WorkContext, fn: () => T): T {
  if (ctx.workspace !== undefined && !isId(ctx.workspace)) throw new Error('bad workspace id');
  if (ctx.user !== undefined && !isId(ctx.user)) throw new Error('bad user id');
  return store.run({ ...ctx }, fn);
}
